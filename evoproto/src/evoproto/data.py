"""Data foundation: provenance, stable seeding, curation controls, source connectors.

Implements Section 3 of the paper:

* Eq. (1)  completeness of a taxon / character in a morphological matrix;
* Eq. (2)  sampling weight of a clade, used when counting independent origins;
* the provenance record pi = (source, version, license, tag, uri, date, r, u)
  of Section 3.3 with its five tags MEASURED / MODELED / PROXY / EXTERNAL /
  SYNTHETIC;
* content-addressed corpus snapshots;
* connectors that expose the Open Tree of Life v3, PBDB v1.2 and MorphoBank
  endpoints.

No biological records are bundled with the package.  The connectors build and
return request URLs; they perform network access only when a caller explicitly
opts in (``allow_network=True``), so that the whole package can be executed and
audited offline (Section 5).
"""

