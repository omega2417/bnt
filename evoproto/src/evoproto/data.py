"""Data foundation: provenance, curation controls and source connectors (Section 3).

Three responsibilities live here:

1. :class:`Provenance` - the five-field record ``(source, version, license, r, u)``
   plus the five-valued :class:`Tag` that is propagated to every number the
   package computes (Section 3.3).
2. The curation controls of Section 3.2 that are expressible as functions:
   :func:`completeness` (Eq. 1) and :func:`sampling_weight` (Eq. 2).
3. Connectors that describe - and, only when explicitly enabled, issue - the
   requests against Open Tree of Life, the Paleobiology Database and
   MorphoBank (Table 2).  The default is offline: the connectors build and
   return the request descriptor so that a corpus snapshot can be assembled,
   audited and licensed deliberately rather than as a side effect of an import.

Seeding (:func:`stable_seed`) is derived with blake2b over
``(package version, task id, arm, replicate)`` rather than Python's built-in
``hash``, which is randomized per process.  This makes every replicate
reproducible across machines and prevents silent seed collisions between arms.
"""

from __future__ import annotations

import datetime as _dt
import hashlib
import json
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import asdict, dataclass, field
from enum import Enum
from typing import Any

