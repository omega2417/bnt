// Package emit implements stage S6 of the GoNext transpiler: printing the
// lowered go/ast tree with go/printer, normalizing it with go/format and
// inserting //line directives so that compiler errors, panics and stack
// traces refer to GoNext source lines.
package emit

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"path/filepath"
	"sort"
	"strings"

	"github.com/ORGANIZATION/gonext/internal/iast"
)

// Options controls emission.
type Options struct {
	LineDirectives bool
	Version        string
}

// File prints the lowered file f of package p.
func File(p *iast.Package, f *iast.File, opt Options) ([]byte, error) {
	file := f.AST
	// drop comments that stood inside lowered match expressions; their
	// anchors no longer exist
	var keep []*ast.CommentGroup
	for _, cg := range file.Comments {
		inside := false
		for _, m := range p.Matches {
			if m.File == f && cg.Pos() > m.Pos && cg.End() < m.End {
				inside = true
			}
		}
		if !inside {
			keep = append(keep, cg)
		}
	}
	file.Comments = keep
	sortImports(file)

	var buf bytes.Buffer
	cfg := printer.Config{Mode: printer.UseSpaces | printer.TabIndent, Tabwidth: 8}
	if err := cfg.Fprint(&buf, p.Fset, file); err != nil {
		return nil, err
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("%s: internal error: generated code is not valid Go: %v\n%s", f.Syn.Path, err, buf.Bytes())
	}
	base := filepath.Base(f.Syn.Path)
	header := fmt.Sprintf("// Code generated by gonext %s from %s. DO NOT EDIT.\n\n", opt.Version, base)
	if !opt.LineDirectives {
		return append([]byte(header), src...), nil
	}
	out, err := directives(p, f, src, base)
	if err != nil {
		return nil, err
	}
	return append([]byte(header), out...), nil
}

func sortImports(f *ast.File) {
	for _, d := range f.Decls {
		g, ok := d.(*ast.GenDecl)
		if !ok || g.Tok != token.IMPORT {
			continue
		}
		if len(g.Specs) > 1 && !g.Lparen.IsValid() {
			g.Lparen = g.TokPos
		}
	}
}

// anchors lists the nodes that start a line of interest, in source order.
func anchors(n ast.Node) []ast.Node {
	var out []ast.Node
	ast.Inspect(n, func(x ast.Node) bool {
		switch x.(type) {
		case *ast.BlockStmt, *ast.EmptyStmt:
		case ast.Stmt, ast.Decl, *ast.ValueSpec, *ast.TypeSpec, *ast.Field:
			out = append(out, x)
		}
		return true
	})
	return out
}

// directives inserts //line directives into the formatted source src of
// file f wherever the implicit line mapping would be wrong.
func directives(p *iast.Package, f *iast.File, src []byte, base string) ([]byte, error) {
	fset2 := token.NewFileSet()
	f2, err := parser.ParseFile(fset2, "", src, parser.ParseComments|parser.SkipObjectResolution)
	if err != nil {
		return nil, err
	}
	a1, a2 := anchors(f.AST), anchors(f2)
	lines := bytes.SplitAfter(src, []byte("\n"))
	want := map[int]int{}
	if len(a1) == len(a2) {
		for i := range a1 {
			if fmt.Sprintf("%T", a1[i]) != fmt.Sprintf("%T", a2[i]) {
				break
			}
			pos, ok := p.Position(a1[i])
			if !ok || pos.Filename != f.Syn.Path || pos.Line == 0 {
				continue
			}
			out := fset2.Position(a2[i].Pos())
			if out.Line < 1 || out.Line > len(lines) {
				continue
			}
			prefix := lines[out.Line-1][:out.Column-1]
			if len(bytes.TrimSpace(prefix)) != 0 {
				continue
			}
			if _, seen := want[out.Line]; !seen {
				want[out.Line] = pos.Line
			}
		}
	}
	// the package clause
	if pos := f.Syn.Position(f.AST.Package); pos.Line > 0 {
		want[fset2.Position(f2.Package).Line] = pos.Line
	}
	// a directive must not separate a declaration from its doc comment:
	// move it above the comment and compensate for the comment lines
	isComment := func(o int) bool {
		t := bytes.TrimSpace(lines[o-1])
		return bytes.HasPrefix(t, []byte("//")) && !bytes.HasPrefix(t, []byte("//go:")) && !bytes.HasPrefix(t, []byte("//line "))
	}
	for o, l := range want {
		top := o
		for top > 1 && isComment(top-1) {
			top--
		}
		if top != o && l-(o-top) >= 1 {
			if _, taken := want[top]; !taken {
				delete(want, o)
				want[top] = l - (o - top)
			}
		}
	}
	outLines := make([]int, 0, len(want))
	for l := range want {
		outLines = append(outLines, l)
	}
	sort.Ints(outLines)
	var b bytes.Buffer
	baseOut, baseOrig := -1, 0
	next := 0
	for i, line := range lines {
		o := i + 1
		if next < len(outLines) && outLines[next] == o {
			next++
			l := want[o]
			if baseOut < 0 || baseOrig+(o-baseOut) != l {
				fmt.Fprintf(&b, "//line %s:%d\n", base, l)
				baseOut, baseOrig = o, l
			}
		}
		b.Write(line)
	}
	// gofmt separates declarations that now carry a comment by blank lines;
	// lines inserted in front of a directive do not change the mapping
	res, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("internal error: %v", err)
	}
	if strings.Count(string(res), "//line ") != strings.Count(b.String(), "//line ") {
		return nil, fmt.Errorf("internal error: line directives lost by formatting")
	}
	return res, nil
}
