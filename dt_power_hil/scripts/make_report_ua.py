def P(text="", bold=False, italic=False, size=None, align=None, color=None, after=None):
    p = doc.add_paragraph()
    _runs(p, text, bold, italic, size, color)
    if align:
        p.alignment = align
    else:
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    if after is not None:
        p.paragraph_format.space_after = Pt(after)
    return p


def _runs(p, text, bold=False, italic=False, size=None, color=None):
    # **bold** inline markup
    parts = text.split("**")
    for i, part in enumerate(parts):
        if not part:
            continue
        r = p.add_run(part)
        r.bold = bold or (i % 2 == 1)
        r.italic = italic
        if size:
            r.font.size = Pt(size)
        if color:
            r.font.color.rgb = RGBColor.from_string(color)


def H(text, lvl=1):
    doc.add_heading(text, level=lvl)


def bullets(items):
    for it in items:
        p = doc.add_paragraph(style="List Bullet")
        _runs(p, it)
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY


def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hexcolor)
    tcPr.append(shd)


def table(caption, header, rows, widths=None, note=None, size=8.5):
    TABN[0] += 1
    c = P(f"**Таблиця {TABN[0]}.** {caption}", size=9.5, after=2)
    c.alignment = WD_ALIGN_PARAGRAPH.LEFT
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(header):
        cell = t.rows[0].cells[i]
        cell.text = ""
        r = cell.paragraphs[0].add_run(h)
        r.bold = True
        r.font.size = Pt(size)
        shade(cell, "E8E7E3")
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ""
            r = cells[i].paragraphs[0].add_run(str(v))
            r.font.size = Pt(size)
    if widths:
        for row in t.rows:
            for i, wdt in enumerate(widths):
                row.cells[i].width = Cm(wdt)
    if note:
        n = P(note, italic=True, size=8.5)
        n.paragraph_format.space_before = Pt(2)
    else:
        doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return TABN[0]


def figure(name, caption, width=16.5):
    FIGN[0] += 1
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.add_run().add_picture(str(FIG / f"{name}.png"), width=Cm(width))
    c = P(f"**Рис. {FIGN[0]}.** {caption}", size=9)
    c.paragraph_format.space_after = Pt(8)
    return FIGN[0]


def box(lines, fill="F4F3F0"):
    t = doc.add_table(rows=1, cols=1)
    t.style = "Table Grid"
    cell = t.rows[0].cells[0]
    shade(cell, fill)
    cell.text = ""
    first = True
    for ln in lines:
        p = cell.paragraphs[0] if first else cell.add_paragraph()
        first = False
        _runs(p, ln, size=9.5)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


