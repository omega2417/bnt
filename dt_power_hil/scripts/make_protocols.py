#!/usr/bin/env python3
"""Generate hardware measurement protocols from the hardware passport and the
emulated E00/E09 results -> hardware/measurement_protocols.md"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "results"
hw = json.load(open(ROOT / "configs" / "hardware_bench_12v.json"))
S = json.load(open(RES / "summary.json"))
cal = json.load(open(RES / "calibration" / "E00_calibration.json"))
cap = S["capacity"]
U = S["uncertainty"]
f = lambda x, n=3: f"{x:.{n}f}".replace(".", ",")  # noqa: E731

L = []
w = L.append
w("# Протоколи вимірювань стенда DT-NODE01-12V\n")
w("Протоколи сформовано автоматично (`scripts/make_protocols.py`) з апаратного паспорта `configs/hardware_bench_12v.json` "
  "і результатів емульованої кампанії. Колонка **EMU** містить значення, отримані на емульованому обладнанні з тими самими "
  "паспортними характеристиками; колонка **ФІЗ** залишена порожньою для заповнення під час фізичного виконання. "
  "Порожня клітинка означає відсутність результату, а не нуль.\n")
w(f"Клас доказовості EMU-значень: *{S['evidence_class']}*. Хеш конфігурації: `{S['config_sha256'][:16]}…`.\n")

LOC = {"M0": "шина після джерела генерації", "M1": "батарейна гілка (знаковий I)", "M2": "вхід критичної гілки",
       "M3": "клеми критичного споживача", "M4": "вхід допоміжної гілки", "M5": "клеми допоміжного споживача",
       "REF": "незалежний батарейний канал, окремий реєстратор RPi4"}
w("## П-1. Паспорт вимірювальних каналів (з характеристик елементів)\n")
w("| Канал | Місце | Вимірювач / шунт | Повна шкала I, А | LSB I, мА | LSB U, мВ | Зміщення нуля max, мА | Некалібр. похибка підсил. max, % | P шунта max, Вт | Рівні калібрування, А |")
w("|---|---|---|---:|---:|---:|---:|---:|---:|---|")
for r in S["channels"]:
    w(f"| {r['channel']} | {LOC[r['channel']]} | {r['meter']} / {r['shunt']} ({f(r['r_shunt_mohm'], 1)} мОм) | {f(r['i_full_scale_a'], 1)} | "
      f"{f(r['i_lsb_ma'], 3)} | {f(r['v_lsb_mv'], 4)} | ±{f(r['offset_max_ma'], 2)} | ±{f(r['uncal_gain_err_max_pct'], 2)} | "
      f"{f(r['p_shunt_max_w'], 2)} | {', '.join(f(x, 2) for x in r['calibration_levels_a'])} |")
w("\nДопуски приймання (розд. 8.1 протоколу): напруга ≤ 0,5 % показу; струм ≤ 1 % показу, біля нуля — абсолютна межа "
  "5·LSB + зміщення; енергія ≤ 2 % на контрольному інтегралі.\n")

w("## П-2. E00 — калібрування нуля й коефіцієнтів\n")
w("Процедура: прогрів за інструкцією приладу; нуль без силового потоку ≥ 60 с (600 відліків при 10 Гц); "
  "п’ять рівнів у робочому діапазоні (для M1/REF — заряд і розряд); коефіцієнти `I_cal = a·I_raw + b` оцінюються за рівнями 1, 3, 5, "
  "верифікація — за рівнями 2, 4; повтор нуля й одного рівня після кампанії (дрейф).\n")
w("| Канал | Нуль (сирий), мА EMU | a EMU | b, мА EMU | Макс. залишок верифікації, % EMU | Критерій ≤ 1 % | a ФІЗ | b ФІЗ | Залишок ФІЗ | Підпис |")
w("|---|---:|---:|---:|---:|---|---|---|---|---|")
for n, c in cal.items():
    w(f"| {n} | {f(c['zero_offset_raw_a'] * 1e3, 2)} | {f(c['a_i'], 5)} | {f(c['b_i'] * 1e3, 2)} | {f(c['max_verification_rel'] * 100, 3)} | "
      f"{'так' if c['pass_current'] else 'НІ'} | | | | |")
w("\n### П-2.1. Рівні калібрування (EMU), канал M1 і REF\n")
for n in ("M1", "REF"):
    w(f"**{n}**\n")
    w("| Рівень, А | Еталон, А | DUT сирий, А | СКВ DUT, мА | DUT калібр., А | Залишок, мА | Залишок, % | Роль | Насичення |")
    w("|---:|---:|---:|---:|---:|---:|---:|---|---|")
    for k, r in enumerate(cal[n]["levels"]):
        w(f"| {f(r['level_a'], 2)} | {f(r['i_std'], 4)} | {f(r['i_dut_mean'], 4)} | {f(r['i_dut_sd'] * 1e3, 2)} | {f(r['i_cal'], 4)} | "
          f"{f(r['residual_a'] * 1e3, 2)} | {f(r['residual_rel'] * 100, 3)} | {'оцінка' if k in (0, 2, 4) else 'верифікація'} | {'так' if r['saturated'] else 'ні'} |")
    w("")

w("## П-3. Бюджет невизначеності (k = 2) каліброваного 1-с значення\n")
w("Складові (k = 1): еталон, залишок калібрування, квантування, шум середнього за 1 с (10 відліків), ТКО шунта при ΔT = 5 °C, "
  "залишкове зміщення після калібрування нуля; для потужності `(u_P/P)² = (u_U/U)² + (u_I/I)²` (розд. 16.5).\n")
w("| Канал | I роб., А | U_I (k=2), мА | U_I, % показу | U_U, % | U_P, % | Домінантна складова I |")
w("|---|---:|---:|---:|---:|---:|---|")
for n, rows in U.items():
    for r in rows:
        dom = max(r["components_i"].items(), key=lambda kv: kv[1])[0]
        w(f"| {n} | {f(r['i_op_a'], 1)} | {f(r['U_i_a_k2'] * 1e3, 2)} | {f(abs(r['U_i_rel_k2']) * 100, 3)} | {f(r['U_v_rel_k2'] * 100, 3)} | "
          f"{f(abs(r['U_p_rel_k2']) * 100, 3)} | {dom} |")
w("\nНаслідок для SOC: залишкове зміщення нуля M1 ≈ ±1,7 мА після калібрування дає дрейф ≤ 0,1 в.п. за 24 год при Q ≈ 38,4 А·год; "
  "невизначеність початкового SOC (±0,4 в.п., 1σ) і Q_ref (≈ 0,1 %) домінують над струмовою складовою на 6-годинних запусках.\n")

w("## П-4. E09 — ємність робочого інтервалу\n")
w("| Параметр | Умова / допуск | EMU | ФІЗ |")
w("|---|---|---:|---|")
rows = [("Заряд до «повного»", "CC 20 А → CV 14,2 В, хвіст 2 А (0,05C)", "виконано", ""),
        ("Відпочинок", "30 хв", "30 хв", ""),
        ("Розряд", "CC 10 А (0,25C) до 11,2 В під навантаженням", f"{f(cap['discharge_time_h'], 2)} год", ""),
        ("Q_ref (REF), А·год", "—", f(cap["q_ref_ah"], 3), ""),
        ("Q_M1 (M1), А·год", "|Q_M1 − Q_ref| ≤ 1 %", f(cap["q_m1_ah"], 3), ""),
        ("E_ref, Вт·год", "—", f(cap["e_ref_wh"], 1), ""),
        ("η_Q (REF) = Ah_out/Ah_in", "0,98–1,00 для LiFePO₄", f(cap["eta_q_ref"], 4), ""),
        ("Температура", "22 ± 2 °C", "22,0", ""),
        ("Прихована істинна ємність (лише в емуляції)", "недоступна у фізичному досліді", f(cap["true_capacity_ah_hidden"], 2), "—")]
for r in rows:
    w(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} |")
w("\nЗауваження: визначено ємність **робочого інтервалу** (14,2 В/2 А … 11,2 В при 10 А), а не повну паспортну ємність (розд. 8.2).\n")

w("## П-5. Попередній контроль перед кожним запуском (розд. 21.2)\n")
for item in ["Паспорти й робочі межі конкретних приладів збережено (П-1 заповнено)",
             "Режим physical / chil_realtime / controller_replay / sil зафіксовано у run-конфігурації",
             "Полярність, запобіжники MIDI 40 А / ATO 25/5/7,5 А, Blue Sea 6006 перевірено",
             "Струм усіх батарейних гілок проходить через M1 і REF (тест: 5 А від RD6018 → |I_M1 − I_REF| ≤ 1 %)",
             "Тест знака: розряд 18 Вт → I_M1 > 0, I_REF > 0; заряд 60 Вт → обидва < 0",
             "Нуль M0–M5, REF: |I| ≤ межі П-1 після 60 с",
             "Реле: команда OFF → M4 < 0,05 А за ≤ 1 с; команда ON → M4 > 1,4 А за ≤ 1 с (EMU: медіана 200 мс)",
             "Watchdog: зупинка heartbeat 6 с → DEGRADED, реле OFF",
             "Початковий SOC_ref у допуску ±1 в.п.; T батареї 20–24 °C",
             "Годинники синхронізовано (SNTP), залишкове зміщення записано (EMU: ±15 мс)",
             "ПК, ESP32, RPi4 — на ДБЖ; вільне місце для журналу ≥ 1 ГБ",
             "run_id, boot_id, хеші конфігурації, прошивки й профілю внесено до протоколу запуску"]:
    w(f"- [ ] {item}")

w("\n## П-6. Протоколи запусків\n")
w("Для кожного з " + str(len(S["runs"])) + " емульованих запусків сформовано протокол у форматі розд. 21.3 протоколу: "
  "`results/protocols/<run_id>.txt`; сирі журнали — `results/raw/<run_id>/` (telemetry_10s.csv, events.csv, commands.csv, edge_log.csv); "
  "контрольні суми — `results/checksums.sha256`. Для фізичного запуску використовувати той самий шаблон, замінивши MODE на `physical` "
  "і заповнивши поля оператора.\n")
w("| run_id | Сценарій | Політика | Тривалість, год | Причина зупинки | Покриття, % | MAE SOC, в.п. | Доставлено LED, Вт·год | Критична недопоставка, Вт·год |")
w("|---|---|---|---:|---|---:|---:|---:|---:|")
for r in S["runs"]:
    if r["scenario_id"] == "E05" and r["repeat"] > 0:
        continue
    w(f"| `{r['run_id']}` | {r['scenario_id']} | {r['policy']} | {f(r['duration_h'], 2)} | {r['stop_reason']} | {f(r['coverage_pct'], 2)} | "
      f"{f(r['mae_soc_pp'], 2)} | {f(r['aux_served_wh'], 1)} | {f(r['critical_unserved_wh'], 1)} |")
w("\n(E05: показано блок R00; повні 10 блоків — `results/metrics_runs.csv`.)\n")

w("## П-7. Картка відхилення (шаблон, розд. 21.6)\n")
w("```text\nDEVIATION_ID:\nRUN_ID:\nWHEN_DETECTED:\nWHAT_HAPPENED:\nAFFECTED_CHANNELS_AND_INTERVAL:\nRAW_DATA_PRESERVED: yes / no with reason\n"
  "ACTION_TAKEN:\nEFFECT_ON_PRIMARY_METRIC:\nELIGIBLE_FOR_ENERGY_ANALYSIS:\nELIGIBLE_FOR_TIMING_ANALYSIS:\nREPEAT_REQUIRED:\nAPPROVED_BY:\n```\n")
(ROOT / "hardware" / "measurement_protocols.md").write_text("\n".join(L), encoding="utf-8")
print("written hardware/measurement_protocols.md")
