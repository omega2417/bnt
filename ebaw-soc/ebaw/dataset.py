INF = math.inf


def _f(x):
    """Finite float or NaN (empty cell)."""
    return float(x) if (x is not None and isinstance(x, (int, float)) and math.isfinite(x)) else float("nan")


def _asset(action: str, k: int) -> str:
    h = int(sha256_hex(f"asset|{k}")[:8], 16)
    if action == "block_ip":
        return f"ip-10.{20 + h % 40}.{(h >> 8) % 256}.{(h >> 16) % 254 + 1}"
    if action in ("revoke_sessions", "disable_account"):
        return f"acct-u{h % 100000:05d}"
    if action == "isolate_server":
        return f"srv-{h % 1000:03d}"
    return f"ws-{h % 10000:04d}"


def _episodes(kept: list, n_eps: int):
    """Group the proposals of one shift into ``n_eps`` episodes.  Malicious, benign and
    adversarial proposals form separate streams (an episode is one incident or one attack on
    the agent); each stream receives a share of the episodes proportional to its size
    (largest remainder, at least one per non-empty stream) and is cut into consecutive,
    nearly equal groups in time order.  Episodes are returned in order of their start."""
    streams = {"malicious": [p for p in kept if p.kind == "gen" and p.y == 1],
               "benign": [p for p in kept if p.kind == "gen" and p.y == 0],
               "adversarial": [p for p in kept if p.kind != "gen"]}
    streams = {k: v for k, v in streams.items() if v}
    n = sum(len(v) for v in streams.values())
    quota = {k: n_eps * len(v) / n for k, v in streams.items()}
    alloc = {k: max(1, int(q)) for k, q in quota.items()}
    while sum(alloc.values()) < n_eps:
        k = max((k for k in streams if alloc[k] < len(streams[k])), key=lambda k: quota[k] - alloc[k])
        alloc[k] += 1
    while sum(alloc.values()) > n_eps:
        k = max((k for k in streams if alloc[k] > 1), key=lambda k: alloc[k] - quota[k])
        alloc[k] -= 1
    eps = []
    for k, v in streams.items():
        for part in np.array_split(np.arange(len(v)), alloc[k]):
            eps.append((k, [v[i] for i in part]))
    eps.sort(key=lambda e: _t_start(e[0], e[1]))
    return eps


def _t_start(label, props):
    """Start of an episode: first observation of an incident; for an attack on the agent, the
    first adversarial proposal (cited evidence may be older and belong to another asset)."""
    return min(p.t_prop for p in props) if label == "adversarial" else min(p.t_obs for p in props)


def scenario_params(did: str, mult: float | None = None) -> dict:
    p = copy.deepcopy(BASE)
    p.update(CATALOG[did]["over"])
    if mult is not None:
        p["surge_mult"] = mult
    return p


