def build(out_dir: str, scenarios=None, progress=print) -> dict:
    """Generate the dataset into ``out_dir``.  Returns the manifest."""
    t0 = time.time()
    os.makedirs(out_dir, exist_ok=True)
    cal = Calibrator(BASE, 42)
    gw_signer = Signer(b"ebaw-soc-synth-gateway", kid="gw-synth-1")
    sensor_signers = {s: Signer(f"sensor|{s}".encode(), kid=s) for s, *_ in SENSORS.values()}
    scenarios = list(CATALOG) if scenarios is None else list(scenarios)
    T = {k: [] for k in SCHEMA}
    asset_counter = 0
    pol_codes = [SHORT[p.name] for p in MAIN_POLICIES]

    for di, did in enumerate(scenarios):
        C = CATALOG[did]
        k_ep = C["proposals"] // C["episodes"]
        need, shift = C["proposals"], 0
        ep_global = 0
        while need > 0:
            mult = C["surge_mults"][shift % 2] if "surge_mults" in C else None
            P = scenario_params(did, mult)
            seed = SEED_BASE + 1000 * (int(did[1:])) + shift
            props = generate(P, seed, cal)
            runs = {code: run(P, props, pol) for code, pol in zip(pol_codes, MAIN_POLICIES)}
            n_keep = min(need, (len(props) // k_ep) * k_ep)
            shift_id = f"{did}-shift{shift:02d}"
            outage = bool(C.get("outage")) and shift % 2 == 1   # validator 5 down in every second shift
            kept = props[:n_keep]

            # ---- identities: one asset per proposal, evidence ids for genuine proposals
            ids = {}
            for p in kept:
                asset_counter += 1
                ids[p.pid] = dict(asset=_asset(p.action, asset_counter), prop=f"{shift_id}-P{p.pid:04d}",
                                  ev=f"{shift_id}-E{p.pid:04d}")
            gen_by_conf = {}
            for p in kept:
                if p.kind == "gen":
                    gen_by_conf.setdefault(round(p.t_conf, 9), p)
            earlier_gen = [p for p in kept if p.kind == "gen"]

            for label, ep_props in _episodes(kept, n_keep // k_ep):
                eid = f"{did}-EP{ep_global:04d}"
                ep_global += 1
                gen = [p for p in ep_props if p.kind == "gen"]
                T["episodes"].append(dict(
                    episode_id=eid, scenario_id=did, scenario_name=C["name"], shift_id=shift_id,
                    techniques=";".join(C["techniques"]), t_start=_t_start(label, ep_props),
                    t_end=max(p.t_prop for p in ep_props), label=label,
                    n_proposals=len(ep_props), n_adversarial=len(ep_props) - len(gen), split=""))
                for p in ep_props:
                    I = ids[p.pid]
                    sensor, cuid, cname, pep = SENSORS[p.action]
                    tech = C["techniques"][int(sha256_hex(I["prop"])[:4], 16) % len(C["techniques"])]
                    A = ACTIONS[p.action]
                    ta, to = TIERS[A["tier"]]
                    refs, tx = [], ""
                    # ---- evidence and ledger anchors
                    if p.kind in ("gen", "tam"):
                        raw = dict(event=I["ev"], asset=I["asset"], t_obs=round(p.t_obs, 6), sensor=sensor,
                                   class_uid=cuid, technique=tech)
                        raw_d = sha256_hex(canonical(raw))
                        score = p.s if p.kind == "gen" else 0.99
                        true_score = p.s if p.kind == "gen" else 0.31
                        rec = lambda sc: sha256_hex(canonical(dict(raw=raw_d, asset=I["asset"],  # noqa: E731
                                                                   t_obs=round(p.t_obs, 6), score=round(sc, 6),
                                                                   src=sensor)))
                        rec_d = rec(score)
                        anchored = p.kind == "gen" or (p.kind == "tam" and math.isfinite(p.t_conf))
                        if anchored:
                            tx = "0x" + sha256_hex("tx|" + I["ev"])[:40]
                            t_sub = (p.t_avail + P["ds"]) if p.kind == "gen" else p.t_conf - 1.0
                            L = p.t_conf - t_sub
                            g = np.random.default_rng([seed, 900, p.pid])
                            fac = np.sort(np.concatenate([g.uniform(0.55, 0.98, 3), [1.0], g.uniform(1.0, 1.6, 1)]))
                            order = g.permutation(N_VALIDATORS)
                            acc = [float("nan")] * N_VALIDATORS
                            for rank, vi in enumerate(order):
                                acc[vi] = t_sub + L * fac[rank]
                            if outage:
                                # the slowest validator crashes; the read quorum of 4 is formed by the rest
                                acc[int(order[-1])] = float("nan")
                            T["ledger_anchors"].append(dict(
                                tx_id=tx, evidence_id=I["ev"], record_digest=rec(true_score), asset_id=I["asset"],
                                t_submit=t_sub, t_final=p.t_conf, Lc=L,
                                **{f"accept_v{i + 1}": acc[i] for i in range(N_VALIDATORS)},
                                t_retract=_f(p.t_ret),
                                retraction_tx_id=("0x" + sha256_hex("ret|" + I["ev"])[:40]) if math.isfinite(p.t_ret) else ""))
                        T["observations"].append(dict(
                            evidence_id=I["ev"], episode_id=eid, asset_id=I["asset"], t_obs=p.t_obs,
                            t_ingest=p.t_avail, sensor=sensor, ocsf_class_uid=cuid, ocsf_class_name=cname,
                            technique=tech, score=score, raw_digest=raw_d, record_digest=rec_d,
                            sensor_signature=sensor_signers[sensor].sign(bytes.fromhex(raw_d)).hex(),
                            tx_id=tx, offchain_tampered=p.kind == "tam"))
                        refs = [I["ev"]]
                    elif p.kind == "hal":
                        ref = gen_by_conf.get(round(p.t_conf, 9))
                        refs = [ids[ref.pid]["ev"]] if ref is not None and ref.pid in ids else ["EV-unresolved"]
                    else:  # injected: cites an unrelated real record or a non-existent one
                        if math.isfinite(p.t_conf) and earlier_gen:
                            ref = earlier_gen[int(sha256_hex(I["prop"])[:6], 16) % len(earlier_gen)]
                            refs = [ids[ref.pid]["ev"]]
                        else:
                            refs = ["EV-" + sha256_hex("fake|" + I["prop"])[:12]]
                    T["proposals"].append(dict(
                        proposal_id=I["prop"], episode_id=eid, scenario_id=did, action=p.action, tier=p.tier,
                        target_asset=I["asset"], evidence_refs=";".join(refs), claimed_conf=p.c_att, t_prop=p.t_prop,
                        rationale="[redacted]", context_digest=sha256_hex("ctx|" + I["prop"]),
                        injection_marker=p.kind == "inj", kind=KIND[p.kind], y_malicious=int(p.y),
                        t_drift=_f(p.t_drift)))
                    part = f"{p.action}:{I['asset']}"
                    common = dict(theta_auto=ta, theta_obs=to, Phi=A["Phi"], D=A["D"])
                    T["policy_snapshots"].append(dict(partition=part, version=0, t_change=0.0, permit=True, **common))
                    hor = P["horizon"] + 3600.0
                    if p.t_pc1 < hor:
                        T["policy_snapshots"].append(dict(partition=part, version=1, t_change=p.t_pc1,
                                                          permit=not p.f1, **common))
                    if p.t_pc2 < hor:
                        T["policy_snapshots"].append(dict(partition=part, version=2, t_change=p.t_pc2,
                                                          permit=not p.f2, **common))
                    # ---- outcomes under every policy
                    for code in pol_codes:
                        r = runs[code][p.pid]
                        dm = None
                        if p.kind == "gen" and p.y == 1:
                            dm = bool(r["executed"] and not r["unsafe"] and (r["t_done"] - r["t_obs"]) <= p.D)
                        T["policy_outcomes"].append(dict(
                            proposal_id=I["prop"], policy=code, outcome=r["outcome"], executed=r["executed"],
                            manual=r["manual"], escalated=r["escalated"], unsafe=r["unsafe"], violation=r["violation"],
                            deadline_met=dm, ttc=_f(r["t_done"] - r["t_obs"]) if r["executed"] else float("nan")))
                    # ---- EB gateway verdict, warrant, execution and analyst action
                    r = runs["EB"][p.pid]
                    ff = r["fails_first"]
                    checked = ff != ""
                    pv = {f"P{i + 1}": ((c not in ff) if checked else None) for i, c in enumerate("FCLVD")}
                    wid, nonce, tok = "", "", ""
                    if math.isfinite(r["t_iss"]):
                        wid = make_wid(I["prop"], round(r["t_iss"], 6))
                        nonce = make_nonce(wid, I["prop"])
                        w = Warrant(wid=wid, act=p.action, tgt=I["asset"],
                                    evd=merkle_root([sha256_hex(x) for x in refs] + ([sha256_hex(tx)] if tx else [])),
                                    pol={"partition": part, "version": 0 if r["t_iss"] < p.t_pc1 else
                                         (1 if r["t_iss"] < p.t_pc2 else 2)},
                                    conf=round(float(p.c_gw), 6), tier=p.tier, regime="AUTO",
                                    iat=round(r["t_iss"], 6), exp=round(_f(r.get("t_exp", INF)), 6)
                                    if math.isfinite(r.get("t_exp", INF)) else 0.0,
                                    nonce=nonce, pred={k: bool(v) for k, v in pv.items() if v is not None})
                        tok = encode(w, gw_signer)
                    T["gateway_verdicts"].append(dict(
                        proposal_id=I["prop"], warrant_id=wid, outcome=r["outcome"], g=float(p.c_gw),
                        regime="AUTO" if p.c_gw >= ta else ("VERIFY" if p.c_gw >= to else "OBSERVE"),
                        **pv, fails_first=ff, fails_reval=r["fails_reval"],
                        fails_all="".join(x for x in "FCLVD" if x in r["fails_all"]),
                        t_chk=_f(r["t_chk"]), age_at_check=_f(r["t_chk"] - p.t_obs), t_iss=_f(r["t_iss"]),
                        t_exp=_f(r.get("t_exp", INF)), t_reval=_f(r["t_reval"]), reverified=r["reverified"],
                        reissued=r["reissued"], lc_timeout=r["lc_timeout"], nonce=nonce, warrant_token=tok))
                    if r["executed"]:
                        dm = bool(not r["unsafe"] and (r["t_done"] - r["t_obs"]) <= p.D) if (p.kind == "gen" and p.y == 1) else None
                        T["executions"].append(dict(
                            proposal_id=I["prop"], enforcement_point=pep, mode="manual" if r["manual"] else "auto",
                            t_disp=_f(r["t_disp"]), t_x=_f(r["t_x"]), t_done=_f(r["t_done"]), window=_f(r["window"]),
                            unsafe=r["unsafe"], violation=r["violation"], viol_set=r["viol_set"], deadline_met=dm))
                    if r["escalated"]:
                        # an approved action can still be stopped by revalidation (retraction, policy)
                        dec = "decline" if r["outcome"] == "analyst_declined" else "approve"
                        T["analyst_actions"].append(dict(
                            proposal_id=I["prop"], t_escalated=_f(r["t_decided"]), urgent=r["urgent"],
                            handling_time=p.analyst_time, decision=dec, correct=p.analyst_correct))
            need -= n_keep
            progress(f"{did} {shift_id}: {n_keep} proposals ({time.time() - t0:.0f} s)")
            shift += 1

    # ---- episode-level temporal split 60/20/20 within every scenario
    ep = pd.DataFrame(T["episodes"])
    for did, g in ep.groupby("scenario_id", sort=False):
        idx = g.sort_values(["shift_id", "t_start"]).index
        n = len(idx)
        n_tr, n_va = int(round(0.6 * n)), int(round(0.2 * n))
        ep.loc[idx[:n_tr], "split"] = "train"
        ep.loc[idx[n_tr:n_tr + n_va], "split"] = "val"
        ep.loc[idx[n_tr + n_va:], "split"] = "test"
    T["episodes"] = ep.to_dict(orient="records")

    files = {}
    for name, cols in SCHEMA.items():
        df = pd.DataFrame(T[name], columns=[c for c, _, _ in cols])
        path = os.path.join(out_dir, f"{name}.csv")
        df.to_csv(path, index=False, float_format="%.6f", lineterminator="\n")
        with open(path, "rb") as fh:
            files[f"{name}.csv"] = dict(sha256=sha256_hex(fh.read()), rows=int(len(df)),
                                        bytes=os.path.getsize(path))
    keys = dict(gateway=dict(kid=gw_signer.kid, alg=gw_signer.alg, public_key=gw_signer.public_bytes.hex()),
                sensors={s: dict(alg=v.alg, public_key=v.public_bytes.hex()) for s, v in sensor_signers.items()})
    with open(os.path.join(out_dir, "keys.json"), "w") as fh:
        json.dump(keys, fh, indent=1)
    _write_datapackage(out_dir)
    root = merkle_root([files[k]["sha256"] for k in sorted(files)])
    manifest = dict(
        name=DATASET_NAME, version=DATASET_VERSION, generator=f"ebaw {__version__}", synthetic=True,
        created_with=dict(python=platform.python_version(), numpy=np.__version__, pandas=pd.__version__),
        seed_base=SEED_BASE, n_validators=N_VALIDATORS, f=F_FAULTY, read_quorum=QUORUM,
        catalog={k: {kk: vv for kk, vv in v.items()} for k, v in CATALOG.items() if k in scenarios},
        files=files, merkle_root=root,
        root_signature=gw_signer.sign(bytes.fromhex(root)).hex(), root_signature_kid=gw_signer.kid)
    with open(os.path.join(out_dir, "manifest.json"), "w") as fh:
        json.dump(manifest, fh, indent=1, default=list)
    progress(f"dataset written to {out_dir} ({time.time() - t0:.0f} s); merkle root {root[:16]}...")
    return manifest


def _write_datapackage(out_dir):
    tmap = {"string": "string", "number": "number", "integer": "integer", "boolean": "boolean"}
    res = []
    for name, cols in SCHEMA.items():
        res.append(dict(name=name, path=f"{name}.csv", format="csv", mediatype="text/csv", encoding="utf-8",
                        schema=dict(fields=[dict(name=c, type=tmap[t], description=d) for c, t, d in cols])))
    pkg = dict(name="ebaw-soc-synth", title=f"{DATASET_NAME} {DATASET_VERSION}: synthetic agentic response episodes "
               "with evidence-bound action warrants", version=DATASET_VERSION,
               licenses=[dict(name="CC-BY-4.0", path="https://creativecommons.org/licenses/by/4.0/")],
               resources=res)
    with open(os.path.join(out_dir, "datapackage.json"), "w") as fh:
        json.dump(pkg, fh, indent=1)


