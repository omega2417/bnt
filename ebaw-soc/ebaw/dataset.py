def load(path: str) -> dict:
    """Load every table into a pandas DataFrame (booleans and empty cells restored)."""
    out = {}
    for name, cols in SCHEMA.items():
        dtypes = {c: ("string" if t == "string" else None) for c, t, _ in cols}
        df = pd.read_csv(os.path.join(path, f"{name}.csv"), dtype={k: v for k, v in dtypes.items() if v},
                         keep_default_na=True)
        for c, t, _ in cols:
            if t == "string":
                df[c] = df[c].fillna("")
            elif t == "boolean":
                df[c] = df[c].map({True: True, False: False, "True": True, "False": False})
        out[name] = df
    return out


def validate(path: str, verbose=True) -> list:
    """Integrity, schema and consistency checks.  Returns the list of failed checks."""
    errs = []
    man = json.load(open(os.path.join(path, "manifest.json")))
    for f, meta in man["files"].items():
        with open(os.path.join(path, f), "rb") as fh:
            if sha256_hex(fh.read()) != meta["sha256"]:
                errs.append(f"digest mismatch: {f}")
    if merkle_root([man["files"][k]["sha256"] for k in sorted(man["files"])]) != man["merkle_root"]:
        errs.append("manifest merkle root mismatch")
    keys = json.load(open(os.path.join(path, "keys.json")))
    from .warrant import Verifier, decode
    gv = Verifier(keys["gateway"]["alg"], bytes.fromhex(keys["gateway"]["public_key"]), keys["gateway"]["kid"])
    if not gv.verify(bytes.fromhex(man["merkle_root"]), bytes.fromhex(man["root_signature"])):
        errs.append("manifest signature invalid")
    D = load(path)
    for name, cols in SCHEMA.items():
        if list(D[name].columns) != [c for c, _, _ in cols]:
            errs.append(f"schema mismatch: {name}")
    P, O, E, V = D["proposals"], D["observations"], D["episodes"], D["gateway_verdicts"]
    if not P.episode_id.isin(E.episode_id).all():
        errs.append("proposal without episode")
    if not O.episode_id.isin(E.episode_id).all():
        errs.append("observation without episode")
    if P.proposal_id.duplicated().any():
        errs.append("duplicate proposal ids")
    anc = D["ledger_anchors"]
    if not anc.evidence_id.isin(O.evidence_id).all():
        errs.append("anchor without observation")
    # sensor signatures (sample of 200) and warrant tokens (sample of 200)
    sv = {s: Verifier(k["alg"], bytes.fromhex(k["public_key"]), s) for s, k in keys["sensors"].items()}
    for _, o in O.head(200).iterrows():
        if not sv[o.sensor].verify(bytes.fromhex(o.raw_digest), bytes.fromhex(o.sensor_signature)):
            errs.append(f"sensor signature invalid: {o.evidence_id}")
            break
    for tok in V.warrant_token[V.warrant_token != ""].head(200):
        if decode(tok, gv) is None:
            errs.append("warrant token does not verify")
            break
    # tampered off-chain records never match their anchors
    m = O.merge(anc[["evidence_id", "record_digest"]], on="evidence_id", how="left", suffixes=("", "_ledger"))
    tam = m[m.offchain_tampered & (m.record_digest_ledger.fillna("") != "")]
    if (tam.record_digest == tam.record_digest_ledger).any():
        errs.append("tampered record matches its ledger anchor")
    gen = m[~m.offchain_tampered]
    if (gen.record_digest != gen.record_digest_ledger).any():
        errs.append("genuine record does not match its ledger anchor")
    # volumes of Table 8
    for did, C in man["catalog"].items():
        if (E.scenario_id == did).sum() != C["episodes"] or (P.scenario_id == did).sum() != C["proposals"]:
            errs.append(f"volume mismatch {did}")
    # headline properties of the full contract
    PO = D["policy_outcomes"].merge(P[["proposal_id", "kind"]], on="proposal_id")
    eb = PO[PO.policy == "EB"]
    if eb[(eb.kind != "genuine")].executed.any():
        errs.append("EB executed an adversarial proposal")
    if eb[eb.executed & ~eb.manual].violation.any():
        errs.append("EB autonomous execution violated the contract")
    if verbose:
        print("validation:", "OK" if not errs else errs)
    return errs
